// Fast free Gemini Flash models
const PRIMARY_MODEL = 'gemini-3.5-flash-lite';
const FALLBACK_MODELS = ['gemini-3.8-flash'];

async function callGeminiWithRetry(params: {
  contents: any;
  config: any;
}): Promise<any> {
  const modelsToTry = [PRIMARY_MODEL, ...FALLBACK_MODELS];
  let lastError: any = null;

  for (const model of modelsToTry) {
    try {
      const res = await ai.models.generateContent({
        model,
        contents: params.contents,
        config: params.config,
      });
      return res;
    } catch (err: any) {
      lastError = err;
      console.warn(`[Gemini Attempt Failed] model=${model}:`, err?.message || err);
      // Wait 500ms before trying the next model
      await new Promise((r) => setTimeout(r, 500));
    }
  }

  throw lastError || new Error('Gemini API call failed across all Flash models');
}

