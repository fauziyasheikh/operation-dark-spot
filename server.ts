// Block private/local IP addresses and protocols
function isBlockedUrl(rawUrl: string): boolean {
  try {
    const parsed = new URL(rawUrl);
    if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') {
      return true;
    }
    const hostname = parsed.hostname.toLowerCase();
    if (
      hostname === 'localhost' ||
      hostname === '0.0.0.0' ||
      hostname === '::1' ||
      hostname === '[::1]' ||
      hostname.endsWith('.local') ||
      hostname.endsWith('.internal')
    ) {
      return true;
    }
    const ipv4Match = hostname.match(/^(\d+)\.(\d+)\.(\d+)\.(\d+)$/);
    if (ipv4Match) {
      const a = Number(ipv4Match[1]);
      const b = Number(ipv4Match[2]);
      if (a === 127 || a === 10 || a === 0) return true;
      if (a === 172 && b >= 16 && b <= 31) return true;
      if (a === 192 && b === 168) return true;
      if (a === 169 && b === 254) return true;
    }
    return false;
  } catch {
    return true;
  }
}

// Normalize text for quote verification
function normalizeText(str: string): string {
  if (!str) return '';
  return str
    .toLowerCase()
    .replace(/[“”"„‟]/g, '"')
    .replace(/[‘’'‚‛]/g, "'")
    .replace(/[—–−]/g, '-')
    .replace(/[…\.]+/g, '.')
    .replace(/\s+/g, ' ')
    .trim();
}

// Verify quote in source text (exact substring or >=85% 5-word n-grams)
function verifyQuoteInText(quote: string, text: string): { verified: boolean; note: string } {
  const normQuote = normalizeText(quote);
  const normText = normalizeText(text);

  if (!normQuote || !normText) {
    return { verified: false, note: 'Empty quote or source text' };
  }

  if (normText.includes(normQuote)) {
    return { verified: true, note: 'Verbatim substring match' };
  }

  // 5-word n-grams check
  const words = normQuote.split(' ').filter(Boolean);
  if (words.length <= 4) {
    const found = normText.includes(words.join(' '));
    return {
      verified: found,
      note: found ? 'Short phrase found' : 'Short phrase not found in source text',
    };
  }

  let totalWindows = 0;
  let matchedWindows = 0;
  for (let i = 0; i <= words.length - 5; i++) {
    totalWindows++;
    const windowStr = words.slice(i, i + 5).join(' ');
    if (normText.includes(windowStr)) {
      matchedWindows++;
    }
  }

  const matchRatio = totalWindows > 0 ? matchedWindows / totalWindows : 0;
  if (matchRatio >= 0.85) {
    return {
      verified: true,
      note: `Verified (${Math.round(matchRatio * 100)}% of 5-word groups matched)`,
    };
  }

  return {
    verified: false,
    note: `Unverified (${Math.round(matchRatio * 100)}% 5-word match, 85% required)`,
  };
}

interface DeclaredDatesResult {
  publishedDate?: string;
  modifiedDate?: string;
  formattedLabel?: string;
  isAutoGeneratedDate: boolean;
}

// Parse declared dates strictly from page markup (Never HTTP Last-Modified)
function extractDeclaredDates($: cheerio.CheerioAPI, html: string, now: Date): DeclaredDatesResult {
  const todayIso = now.toISOString().split('T')[0];

  const parseIso = (val?: string): string | undefined => {
    if (!val || typeof val !== 'string') return undefined;
    const clean = val.trim();
    if (clean.length < 4) return undefined;
    const t = Date.parse(clean);
    if (!isNaN(t)) {
      return new Date(t).toISOString().split('T')[0];
    }
    const match = clean.match(/\b(20\d\d|19\d\d)[-/](0[1-9]|1[0-2])[-/](0[1-9]|[12]\d|3[01])\b/);
    if (match) return match[0].replace(/\//g, '-');
    return clean.slice(0, 30);
  };

  // Published candidates
  const pubCandidates = [
    $('meta[property="article:published_time"]').attr('content'),
    $('meta[name="article:published_time"]').attr('content'),
    $('meta[name="date"]').attr('content'),
    $('meta[name="pubdate"]').attr('content'),
    $('*[itemprop="datePublished"]').attr('content') || $('*[itemprop="datePublished"]').text(),
    $('time[datetime]').first().attr('datetime'),
    $('time').first().text(),
  ];
  let pubDate: string | undefined;
  for (const c of pubCandidates) {
    const parsed = parseIso(c);
    if (parsed) {
      pubDate = parsed;
      break;
    }
  }

  // Modified candidates
  const modCandidates = [
    $('meta[property="article:modified_time"]').attr('content'),
    $('meta[name="article:modified_time"]').attr('content'),
    $('meta[property="og:updated_time"]').attr('content'),
    $('*[itemprop="dateModified"]').attr('content') || $('*[itemprop="dateModified"]').text(),
  ];
  let modDate: string | undefined;
  for (const c of modCandidates) {
    const parsed = parseIso(c);
    if (parsed) {
      modDate = parsed;
      break;
    }
  }

  // Check JSON-LD
  const jsonLdElements = $('script[type="application/ld+json"]').toArray();
  for (const elem of jsonLdElements) {
    try {
      const raw = $(elem).html();
      if (raw) {
        const json = JSON.parse(raw);
        const obj = json['@graph'] ? json['@graph'][0] : json;
        if (!pubDate && obj?.datePublished) pubDate = parseIso(obj.datePublished);
        if (!modDate && obj?.dateModified) modDate = parseIso(obj.dateModified);
      }
    } catch {
      // ignore
    }
  }

  const isAutoGenerated = pubDate === todayIso || modDate === todayIso;

  let formattedLabel: string | undefined;
  if (pubDate && modDate && pubDate !== modDate) {
    formattedLabel = `page-declared date: Published ${pubDate} • Modified ${modDate}`;
  } else if (pubDate) {
    formattedLabel = `page-declared date: Published ${pubDate}`;
  } else if (modDate) {
    formattedLabel = `page-declared date: Modified ${modDate}`;
  }

  if (formattedLabel && isAutoGenerated) {
    formattedLabel += ' (Date may be auto-generated)';
  }

  return {
    publishedDate: pubDate,
    modifiedDate: modDate,
    formattedLabel,
    isAutoGeneratedDate: isAutoGenerated,
  };
}

// Compute freshness in code: fresh (<=180 days), aging (<=540), old, undated
// If declared date equals today, do not mark it Fresh
function computeFreshness(
  declared: DeclaredDatesResult,
  cleanText: string,
  now: Date
): { freshness: SourceFreshness; resolvedDate?: string; latestYear?: number; isAutoGeneratedDate?: boolean } {
  const currentYear = now.getFullYear();

  // Find latest year mentioned in text
  const yearMatches = cleanText.match(/\b(19\d\d|20\d\d)\b/g);
  let latestYear: number | undefined;
  if (yearMatches) {
    const numericYears = yearMatches.map(Number).filter((y) => y >= 1990 && y <= currentYear + 2);
    if (numericYears.length > 0) {
      latestYear = Math.max(...numericYears);
    }
  }

  // If a declared date equals today's date, show "Date may be auto-generated" and do not mark it Fresh
  if (declared.isAutoGeneratedDate) {
    return {
      freshness: 'aging',
      resolvedDate: declared.formattedLabel,
      latestYear,
      isAutoGeneratedDate: true,
    };
  }

  const refDate = declared.modifiedDate || declared.publishedDate;
  if (refDate) {
    const timestamp = Date.parse(refDate);
    if (!isNaN(timestamp)) {
      const diffDays = (now.getTime() - timestamp) / (1000 * 60 * 60 * 24);
      if (diffDays <= 180) {
        return { freshness: 'fresh', resolvedDate: declared.formattedLabel, latestYear };
      }
      if (diffDays <= 540) {
        return { freshness: 'aging', resolvedDate: declared.formattedLabel, latestYear };
      }
      return { freshness: 'old', resolvedDate: declared.formattedLabel, latestYear };
    }
    return { freshness: 'aging', resolvedDate: declared.formattedLabel, latestYear };
  }

  // If no date and latest year in text is before current year (2026), mark old
  if (latestYear && latestYear < currentYear) {
    return {
      freshness: 'old',
      resolvedDate: `page-declared date: Undated (Latest year cited in text: ${latestYear})`,
      latestYear,
    };
  }

  return { freshness: 'undated', resolvedDate: undefined, latestYear };
}

// Limit character line to max 18 words
function limitWords(str: string, maxWords = 18): string {
  if (!str) return '';
  const words = str.trim().split(/\s+/);
  if (words.length <= maxWords) return str;
  return words.slice(0, maxWords).join(' ') + '...';
}

