export type AvatarId = 'shinchan' | 'misae' | 'kazama' | 'masao' | 'shiro';

export type DashboardTab = 'gaps' | 'conflicts' | 'outdated' | 'checklist';

export type FindingBadge = 'Sourced' | 'AI suggestion' | 'Uncertain';

export type SourceFreshness = 'fresh' | 'aging' | 'old' | 'undated';

export type SourceType = 'official' | 'third-party' | 'forum' | 'archive' | 'unknown';

export interface AvatarConfig {
  id: AvatarId;
  name: string;
  emoji: string;
  title: string;
  accentColor: string; // Background / highlight
  inkColor: string; // Avatar's distinct ink / punch color
  cardBg: string;
  defaultTab: DashboardTab;
  quotes: {
    login: string;
    newCase: string;
    tip: string;
    dashboardGreeting: string;
  };
  personalityNote: string;
}

export interface UserSession {
  uid: string;
  displayName: string;
  avatar: AvatarId;
  xp: number;
  badges: string[];
  casesClosed: number;
  createdAt: string;
  isGuest: boolean;
}

export interface SourceInput {
  url: string;
  type?: SourceType;
  pastedText?: string;
}

export interface FetchedSource {
  id: string; // S1, S2, ...
  url: string;
  type: SourceType;
  status: 'success' | 'failed';
  note?: string;
  title: string;
  domain: string;
  text: string;
  declaredDate?: string; // e.g. "page-declared date: Published 2026-03-29 • Modified 2026-10-15"
  publishedDate?: string;
  modifiedDate?: string;
  isAutoGeneratedDate?: boolean;
  freshness: SourceFreshness;
  authorOrDept?: string;
  latestYearFound?: number;
  bestClaimQuote?: string; // Best verified claim quote for source card preview
}

export interface ExtractedClaim {
  id: string; // e.g. S1-C1
  sourceId: string;
  topic: string;
  claim: string;
  quote: string;
  verified: boolean;
  verificationNote?: string;
}

export interface QuoteVerification {
  quote: string;
  sourceId: string;
  sourceTitle: string;
  sourceUrl: string;
  pageOrSection?: string;
  dateCited?: string;
  isVerifiedInSourceText: boolean;
}

export interface GapFinding {
  id: string;
  title: string;
  topic: string;
  badge: FindingBadge;
  description: string;
  impact?: string;
  characterLine: string;
  recommendedAction?: string;
  sourceQuote?: QuoteVerification;
}

export interface ConflictFinding {
  id: string;
  title: string;
  topic: string;
  badge: FindingBadge;
  description: string;
  claimIdA: string;
  claimIdB: string;
  quoteA: QuoteVerification;
  quoteB: QuoteVerification;
  characterLine: string;
  resolutionNote?: string;
}

export interface OutdatedFinding {
  id: string;
  title: string;
  topic?: string;
  badge: FindingBadge;
  description: string;
  statedYearOrDate: string;
  currentStandardDate: string;
  quote: QuoteVerification;
  characterLine: string;
  warning?: string;
  isDateBasedCodeFlag?: boolean;
}

export interface ChecklistItem {
  id: string;
  task: string;
  category: 'gaps' | 'conflicts' | 'outdated' | 'general';
  priority: 'high' | 'medium' | 'low';
  cleared: boolean;
  xpReward: number; // 25 for high, 15 for medium, 10 for low
  clearedAt?: string;
  referenceQuote?: QuoteVerification;
  note: string;
  clearsSpotId?: string; // links to gap or conflict of same topic
  topic?: string;
  characterLine?: string;
}

export interface AnalysisStats {
  sourcesReviewed: number;
  claimsUsed: number;
  claimsRejected: number;
  findingsDropped: number;
  totalClaimsExtracted: number;
  claimsVerified: number;
}

export interface CaseData {
  id: string;
  caseNumber: string;
  title: string;
  targetQuestion: string;
  targetSources: SourceInput[];
  openedDate: string;
  status: 'Investigating' | 'Resolved' | 'Dormant';
  sources: FetchedSource[];
  claims?: ExtractedClaim[];
  gaps: GapFinding[];
  conflicts: ConflictFinding[];
  outdated: OutdatedFinding[];
  checklist: ChecklistItem[];
  stats?: AnalysisStats;
  expectedTopics?: string[];
}
